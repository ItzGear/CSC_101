import turtle

def draw_square():
    # Fixed side length for the square
    side_length = 100

    # Draw a square
    for _ in range(4):
        turtle.forward(side_length)  # Move forward by side_length
        turtle.right(90)              # Turn right by 90 degrees

# Set up the turtle environment
turtle.speed(1)  # Set speed of drawing (1 is slowest, 10 is fastest)

# Draw first square
draw_square()

# Move to a new position for second square
turtle.penup()   # Lift pen so it doesn't draw while moving
turtle.goto(150, 0)  # Move to new coordinates (150, 0)
turtle.pendown() # Put pen down to start drawing

# Draw second square
draw_square()

# Move to a new position for third square
turtle.penup()
turtle.goto(-150, 0)  # Move to new coordinates (-150, 0)
turtle.pendown()

# Draw third square
draw_square()

# Finish drawing
turtle.done()

