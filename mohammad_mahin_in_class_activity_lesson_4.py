def find_even_numbers():
    even_numbers = []  # Step 2: Initialize an empty list
    for num in range(11):  # Step 3: Loop through numbers from 0 to 10
        if num % 2 == 0:   # Step 4: Check if the number is even
            even_numbers.append(num)  # Step 5: Append to list if it's even
    print(even_numbers)   # Step 6: Print the list of even numbers

# Call the function to see results
find_even_numbers()